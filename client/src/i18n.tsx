type LanguageContextValue = {
  lang: AppLanguage;
  setLang: (lang: AppLanguage) => void;
  t: (text: string) => string;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

function readStoredLang(): AppLanguage {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === 'mr' || stored === 'en') return stored;
  } catch {
    /* ignore */
  }
  return 'en';
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<AppLanguage>(() => readStoredLang());

  const setLang = useCallback((next: AppLanguage) => {
    setLangState(next);
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch {
      /* ignore */
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang === 'mr' ? 'mr' : 'en';
    document.documentElement.dataset.lang = lang;
  }, [lang]);

  const t = useCallback(
    (text: string) => {
      if (!text || lang === 'en') return text;
      return mr[text] ?? text;
    },
    [lang],
  );

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) {
    return {
      lang: 'en' as AppLanguage,
      setLang: () => undefined,
      t: (text: string) => text,
    };
  }
  return ctx;
}

export function useT() {
  return useLanguage().t;
}

export function LanguageSwitcher({ className = '' }: { className?: string }) {
  const { lang, setLang, t } = useLanguage();

  return (
    <div className={`lang-switcher${className ? ` ${className}` : ''}`} role="group" aria-label={t('Language')}>
      <button
        type="button"
        className={`lang-switcher-btn${lang === 'en' ? ' is-active' : ''}`}
        aria-pressed={lang === 'en'}
        onClick={() => setLang('en')}
      >
        EN
      </button>
      <button
        type="button"
        className={`lang-switcher-btn${lang === 'mr' ? ' is-active' : ''}`}
        aria-pressed={lang === 'mr'}
        onClick={() => setLang('mr')}
      >
        मराठी
      </button>
    </div>
  );
}
